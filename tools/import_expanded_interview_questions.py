def build_sql():
    lines = [
        "-- ============================================================",
        "-- 由 tools/import_expanded_interview_questions.py 生成",
        "-- 来源：团队收集的《面试题》docx 合集（14 个非 Java-后端方向，共 15 份文件），",
        "-- 覆盖 Go/Python/前端/大数据/Android/iOS/测试/运维/网络安全/数据分析/数据库/",
        "-- 游戏开发等方向。key_points 是提炼过的要点提示，不是原文逐字转录（原因见本",
        "-- 脚本文件头注释）。这是开放式问答，供「学习资料/面试准备」阅读用，",
        "-- 不是自动判分的 questions 表。",
        "-- ============================================================",
        "",
        "SET NAMES utf8mb4;",
        "",
        "-- ---------- 1) 新岗位类别 ----------",
    ]
    for name, desc in NEW_JOB_CATEGORIES:
        lines.append(
            "INSERT INTO job_categories (name, major_id, description, status) "
            f"SELECT {esc(name)}, 1, {esc(desc)}, 'active' "
            f"WHERE NOT EXISTS (SELECT 1 FROM job_categories WHERE name = {esc(name)});"
        )
    lines.append("")
    lines.append("-- ---------- 2) 新技能节点 ----------")
    for name, domain, aliases, difficulty, est_hours in NEW_SKILLS:
        alias_json = json_array(aliases)
        lines.append(
            "INSERT INTO skills (name, domain, aliases, difficulty, est_hours) "
            f"SELECT {esc(name)}, {esc(domain)}, {esc(alias_json)}, {difficulty}, {est_hours} "
            f"WHERE NOT EXISTS (SELECT 1 FROM skills WHERE name = {esc(name)});"
        )
    lines.append("")
    lines.append("-- ---------- 3) 面试题（按来源 docx 分组） ----------")
    current_cat = None
    for category_file, skill_name, question, key_points in QUESTIONS:
        if category_file != current_cat:
            current_cat = category_file
            lines.append(f"\n-- 来源：面试题/{category_file}.docx")
        source = f"面试题合集/{category_file}"
        lines.append(
            "INSERT INTO interview_questions (skill_id, question_text, key_points, source) VALUES ("
            f"(SELECT id FROM skills WHERE name = {esc(skill_name)} LIMIT 1), "
            f"{esc(question)}, {esc(key_points)}, {esc(source)});"
        )
    return "\n".join(lines) + "\n"


def main():
    sql = build_sql()
    OUT.write_text(sql, encoding="utf-8")
    print(f"新增岗位类别 {len(NEW_JOB_CATEGORIES)} 个，技能 {len(NEW_SKILLS)} 个，面试题 {len(QUESTIONS)} 道")
    print(f"已写入 {OUT}")


if __name__ == "__main__":
    main()

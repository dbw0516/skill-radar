def json_array(items):
    """构造合法的 JSON 数组字面量——不能直接用 esc()，那是单引号 SQL 字符串转义，
    aliases 是 JSON 类型的列，数组里的字符串必须是双引号，MySQL 才认。"""
    def jesc(s):
        return str(s).replace("\\", "\\\\").replace('"', '\\"')
    return "[" + ", ".join(f'"{jesc(a)}"' for a in items) + "]"


def esc(s):
    """反斜杠转义 + 单引号双写——mysql 命令行客户端读 .sql 文件时对 \\' 有解析歧义，
    这是之前导入天池数据集时踩过的坑，这里沿用同一个转义规则。"""
    if s is None:
        return "NULL"
    s = str(s).strip().replace("\\", "\\\\").replace("'", "''")
    return f"'{s}'"


